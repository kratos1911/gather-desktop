"""Capture an existing extractor environment as a Linux/amd64 wheel hash lock.

Run deliberately after reviewing version changes. Uses an ephemeral Docker
container to resolve public PyPI artifacts; no host packages are installed.
"""
import argparse
import json
from pathlib import Path
import re
import subprocess
import uuid

ROOT = Path(__file__).resolve().parents[1]


def docker_python(image, code, payload=None, offline=False):
    container = 'gather-lock-' + uuid.uuid4().hex
    command = ['docker', 'run', '--rm', '--name', container, '-i', '--platform', 'linux/amd64']
    if offline:
        command += ['--network', 'none']
    command += ['--entrypoint', 'python', image, '-c', code]
    try:
        result = subprocess.run(command, input=payload, capture_output=True, timeout=600)
    finally:
        # Remove only this invocation's container, including after timeout.
        subprocess.run(['docker', 'rm', '-f', container], capture_output=True, timeout=30)
    if result.returncode:
        raise RuntimeError(result.stderr.decode('utf-8', errors='replace')[-3000:])
    return json.loads(result.stdout)


def normalize(name):
    return re.sub(r'[-_.]+', '-', name).lower()


def lock_from_report(report, expected):
    rows = []
    inventory = []
    seen = set()
    for package in sorted(report['install'], key=lambda p: normalize(p['metadata']['name'])):
        metadata = package['metadata']
        name, version = normalize(metadata['name']), metadata['version']
        download = package['download_info']
        digest = download['archive_info']['hashes']['sha256']
        url = download['url']
        if (name in seen or expected.get(name) != version
                or not re.fullmatch(r'[0-9a-f]{64}', digest)
                or not url.startswith('https://files.pythonhosted.org/')
                or not url.endswith('.whl')):
            raise ValueError('Unexpected package, version or wheel artifact')
        seen.add(name)
        rows.append(f'{name}=={version} --hash=sha256:{digest}')
        inventory.append({
            'name': name, 'version': version, 'wheel': url, 'sha256': digest,
            'license_expression': metadata.get('license_expression'),
            'license_classifiers': [c for c in metadata.get('classifier', [])
                                    if c.startswith('License ::')],
            'license_metadata': metadata.get('license', ''),
            'license_files': metadata.get('license_file', []),
        })
    if seen != set(expected):
        raise ValueError('Resolver omitted locked packages')
    return rows, inventory


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--image', required=True, help='Reviewed image ID to freeze')
    args = parser.parse_args()
    packages = docker_python(args.image, '''import importlib.metadata as m, json
print(json.dumps({d.metadata['Name']: d.version for d in m.distributions()
                  if d.metadata['Name'].lower() != 'pip'}))''', offline=True)
    expected = {normalize(name): version for name, version in packages.items()}
    payload = '\n'.join(f'{name}=={version}' for name, version in sorted(expected.items())).encode()
    report = docker_python(args.image, '''import pathlib, subprocess, sys
p = pathlib.Path('/tmp/gather-pins.txt')
p.write_bytes(sys.stdin.buffer.read())
subprocess.run([sys.executable, '-m', 'pip', '--isolated', 'install',
 '--dry-run', '--ignore-installed', '--only-binary=:all:', '--disable-pip-version-check',
 '--no-cache-dir', '--index-url', 'https://pypi.org/simple', '--quiet', '--report', '-',
 '-r', str(p)], check=True)''', payload)
    rows, inventory = lock_from_report(report, expected)
    header = ('# Linux/amd64, CPython 3.12. Wheel artifacts only.\n'
              '# Generated by scripts/lock_extractor.py from a reviewed image.\n'
              '# Bootstrap pip is pinned separately in requirements-bootstrap.lock.\n')
    worker = ROOT / 'services' / 'worker'
    (worker / 'requirements-extraction.lock').write_text(header + '\n'.join(rows) + '\n', encoding='utf-8')
    (worker / 'extraction-packages.json').write_text(json.dumps({
        'schema_version': 1, 'target': 'linux/amd64 CPython 3.12',
        'source_image': args.image, 'packages': inventory,
        'notice': 'Declared wheel metadata, not a license/legal certification. Preserve bundled notices.',
    }, indent=2) + '\n', encoding='utf-8')
    print(f'Locked {len(rows)} wheel artifacts and recorded declared license metadata.')


if __name__ == '__main__':
    main()
